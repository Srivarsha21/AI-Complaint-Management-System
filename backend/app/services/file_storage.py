"""Validation and storage of uploaded complaint images.

The file type is decided from the file's leading bytes ("magic numbers"), never
from the client-supplied name or Content-Type, and the file must also decode
with OpenCV (corrupt or disguised files are rejected). Files are stored under random
names outside any web-served folder and are only returned through an
authorized endpoint.
"""

import logging
import uuid
from dataclasses import dataclass
from pathlib import Path, PurePath

import numpy as np
from fastapi import UploadFile

from app.ai.vision import quality
from app.core.config import get_settings
from app.core.errors import BadRequestError

logger = logging.getLogger(__name__)

_CHUNK = 64 * 1024


@dataclass(frozen=True)
class StoredFile:
    original_filename: str
    stored_filename: str
    content_type: str
    size_bytes: int


def detect_image_type(head: bytes) -> tuple[str, str] | None:
    """Return (content_type, extension) for supported images, else None."""
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg", ".jpg"
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png", ".png"
    if len(head) >= 12 and head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "image/webp", ".webp"
    return None


def _safe_original_name(name: str | None) -> str:
    base = PurePath(name or "image").name.replace("\\", "_")
    cleaned = "".join(ch for ch in base if ch.isprintable()).strip() or "image"
    return cleaned[-120:]


@dataclass(frozen=True)
class ValidatedImage:
    label: str
    data: bytes
    content_type: str
    extension: str
    image: np.ndarray  # decoded BGR pixels


def read_validated_image(upload: UploadFile) -> ValidatedImage:
    """Read an upload and check size, magic bytes and that OpenCV can decode it.

    Raises BadRequestError with a user-facing message on any failure.
    """
    settings = get_settings()
    max_bytes = settings.max_upload_size_mb * 1024 * 1024
    label = _safe_original_name(upload.filename)

    data = bytearray()
    while chunk := upload.file.read(_CHUNK):
        data.extend(chunk)
        if len(data) > max_bytes:
            raise BadRequestError(f"'{label}' is larger than {settings.max_upload_size_mb} MB.")
    if not data:
        raise BadRequestError(f"'{label}' is empty.")
    raw = bytes(data)

    detected = detect_image_type(raw[:16])
    if detected is None:
        raise BadRequestError(f"'{label}' is not a supported image. Use JPEG, PNG or WebP.")
    content_type, extension = detected

    # A valid header is not enough: the pixels must actually decode. The size is
    # checked from the header first so a tiny file cannot expand into a huge bitmap.
    unreadable = f"'{label}' could not be read as an image. It may be corrupt; please choose another photo."
    dimensions = quality.image_dimensions(raw)
    if dimensions is None:
        raise BadRequestError(unreadable)
    if dimensions[0] * dimensions[1] > settings.max_image_pixels:
        raise BadRequestError(f"'{label}' has too many pixels. Please use a smaller photo.")
    image = quality.decode_image(raw)
    if image is None:
        raise BadRequestError(unreadable)

    return ValidatedImage(label=label, data=raw, content_type=content_type, extension=extension, image=image)


def save_image(upload: UploadFile) -> StoredFile:
    settings = get_settings()
    validated = read_validated_image(upload)
    label, data = validated.label, validated.data
    content_type, extension = validated.content_type, validated.extension

    directory = settings.upload_path / "complaints"
    directory.mkdir(parents=True, exist_ok=True)
    stored_filename = f"{uuid.uuid4().hex}{extension}"
    (directory / stored_filename).write_bytes(data)

    return StoredFile(
        original_filename=label, stored_filename=stored_filename, content_type=content_type, size_bytes=len(data)
    )


def path_for(stored_filename: str) -> Path:
    # Stored names are generated by us, but guard against path tricks anyway.
    if PurePath(stored_filename).name != stored_filename:
        raise BadRequestError("Invalid file reference.")
    return get_settings().upload_path / "complaints" / stored_filename


def delete_quietly(stored_filename: str) -> None:
    try:
        path_for(stored_filename).unlink(missing_ok=True)
    except OSError as exc:
        logger.warning("could not delete upload %s: %s", stored_filename, exc.__class__.__name__)
